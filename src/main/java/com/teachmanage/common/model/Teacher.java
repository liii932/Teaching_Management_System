package com.teachmanage.common.model;

public class Teacher {
    private String tno;
    private String tname;
    private String tsex;
    private String ttitle;
    private String classNo;
    private String className;

    public String getTno() { return tno; }
    public void setTno(String tno) { this.tno = tno; }
    public String getTname() { return tname; }
    public void setTname(String tname) { this.tname = tname; }
    public String getTsex() { return tsex; }
    public void setTsex(String tsex) { this.tsex = tsex; }
    public String getTtitle() { return ttitle; }
    public void setTtitle(String ttitle) { this.ttitle = ttitle; }
    public String getClassNo() { return classNo; }
    public void setClassNo(String classNo) { this.classNo = classNo; }
    public String getClassName() { return className; }
    public void setClassName(String className) { this.className = className; }
}
